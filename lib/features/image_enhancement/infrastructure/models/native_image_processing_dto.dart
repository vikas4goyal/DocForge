/// The currently supported platform-channel message schema.
const nativeImageProcessingSchemaVersion = 1;

/// The currently supported colour-pipeline contract.
const nativeImageProcessingColourPipelineVersion = 1;

/// Serializable homography coefficients in row-major order.
@freezed
abstract class NativeHomographyDto with _$NativeHomographyDto {
  /// Creates a serializable homography.
  const factory NativeHomographyDto({
    required double h00,
    required double h01,
    required double h02,
    required double h10,
    required double h11,
    required double h12,
    required double h20,
    required double h21,
  }) = _NativeHomographyDto;

  /// Deserializes a homography generated by a native response or fixture.
  factory NativeHomographyDto.fromJson(Map<String, dynamic> json) =>
      _$NativeHomographyDtoFromJson(json);

  const NativeHomographyDto._();

  /// Converts [value] into the channel representation.
  ///
  /// Returns an immutable DTO and does not throw for a finite or non-finite
  /// value; request validation rejects non-finite geometry before submission.
  factory NativeHomographyDto.fromDomain(Homography value) =>
      NativeHomographyDto(
        h00: value.h00,
        h01: value.h01,
        h02: value.h02,
        h10: value.h10,
        h11: value.h11,
        h12: value.h12,
        h20: value.h20,
        h21: value.h21,
      );

  /// Converts this DTO into a domain [Homography].
  ///
  /// Returns the coefficient-preserving value. It does not validate finiteness;
  /// [ImageRenderRequest.validate] performs that boundary check.
  Homography toDomain() => Homography(
    h00: h00,
    h01: h01,
    h02: h02,
    h10: h10,
    h11: h11,
    h12: h12,
    h20: h20,
    h21: h21,
  );
}

