/// The versioned request submitted to native image processing.
@freezed
abstract class NativeImageRenderRequestDto with _$NativeImageRenderRequestDto {
  /// Creates a native render request.
  const factory NativeImageRenderRequestDto({
    required int schemaVersion,
    required String requestId,
    required String sourcePath,
    required String destinationPath,
    required ImageRenderScale scale,
    required NativeEnhancementSettingsDto enhancement,
    required int jpegQuality,
    required int colourPipelineVersion,
    NativeHomographyDto? transform,
    int? outputWidth,
    int? outputHeight,
    int? maximumPreviewDimension,
  }) = _NativeImageRenderRequestDto;

  /// Deserializes generated request JSON.
  factory NativeImageRenderRequestDto.fromJson(Map<String, dynamic> json) =>
      _$NativeImageRenderRequestDtoFromJson(json);

  const NativeImageRenderRequestDto._();

  /// Converts [request] into the current native schema.
  ///
  /// Returns the generated DTO. Throws [ArgumentError] when [request] fails
  /// domain validation, before any platform call is attempted.
  factory NativeImageRenderRequestDto.fromDomain(ImageRenderRequest request) {
    request.validate();
    return NativeImageRenderRequestDto(
      schemaVersion: nativeImageProcessingSchemaVersion,
      requestId: request.requestId,
      sourcePath: request.sourcePath,
      destinationPath: request.destinationPath,
      scale: request.scale,
      enhancement: NativeEnhancementSettingsDto.fromDomain(request.enhancement),
      jpegQuality: request.jpegQuality,
      colourPipelineVersion: request.colourPipelineVersion,
      transform: request.transform == null
          ? null
          : NativeHomographyDto.fromDomain(request.transform!),
      outputWidth: request.outputWidth,
      outputHeight: request.outputHeight,
      maximumPreviewDimension: request.maximumPreviewDimension,
    );
  }

  /// Converts this versioned DTO into a validated domain request.
  ///
  /// Returns [ImageRenderRequest]. Throws [FormatException] for an unsupported
  /// schema or colour-pipeline version and [ArgumentError] for invalid values.
  ImageRenderRequest toDomain() {
    _requireSchema(schemaVersion);
    if (colourPipelineVersion != nativeImageProcessingColourPipelineVersion) {
      throw FormatException(
        'unsupported colour pipeline version: $colourPipelineVersion',
      );
    }
    final request = ImageRenderRequest(
      requestId: requestId,
      sourcePath: sourcePath,
      destinationPath: destinationPath,
      scale: scale,
      enhancement: enhancement.toDomain(),
      jpegQuality: jpegQuality,
      colourPipelineVersion: colourPipelineVersion,
      transform: transform?.toDomain(),
      outputWidth: outputWidth,
      outputHeight: outputHeight,
      maximumPreviewDimension: maximumPreviewDimension,
    );
    return request..validate();
  }
}

/// The versioned capability returned by a native backend.
@freezed
abstract class NativeImageProcessingCapabilityDto
    with _$NativeImageProcessingCapabilityDto {
  /// Creates a native capability response.
  const factory NativeImageProcessingCapabilityDto({
    required int schemaVersion,
    required ImageProcessingBackendKind backend,
    required bool isSupported,
    required int maximumTextureSize,
    required bool supportsTiling,
  }) = _NativeImageProcessingCapabilityDto;

  /// Deserializes generated capability JSON.
  factory NativeImageProcessingCapabilityDto.fromJson(
    Map<String, dynamic> json,
