/// The versioned success-or-failure envelope returned by native processing.
@freezed
abstract class NativeImageProcessingResponseDto
    with _$NativeImageProcessingResponseDto {
  /// Creates a response containing exactly one of [result] or [failureKind].
  const factory NativeImageProcessingResponseDto({
    required int schemaVersion,
    NativeImageProcessingResultDto? result,
    ImageProcessingFailureKind? failureKind,
    String? debugDetail,
  }) = _NativeImageProcessingResponseDto;

  /// Deserializes generated response JSON.
  factory NativeImageProcessingResponseDto.fromJson(
    Map<String, dynamic> json,
  ) => _$NativeImageProcessingResponseDtoFromJson(json);

  const NativeImageProcessingResponseDto._();

  /// Converts this envelope into a typed backend response.
  ///
  /// Returns success or failure. Throws [FormatException] when the schema is
  /// unsupported or the envelope contains both/neither outcome.
  ImageProcessingBackendResponse toDomain() {
    _requireSchema(schemaVersion);
    final hasResult = result != null;
    final hasFailure = failureKind != null;
    if (hasResult == hasFailure) {
      throw const FormatException(
        'native response must contain exactly one result or failureKind',
      );
    }
    if (result case final value?) {
      return ImageProcessingBackendResponse.success(value.toDomain());
    }
    return ImageProcessingBackendResponse.failure(
      kind: failureKind!,
      debugDetail: debugDetail,
    );
  }
}

void _requireSchema(int actual) {
  if (actual != nativeImageProcessingSchemaVersion) {
    throw FormatException('unsupported image-processing schema: $actual');
  }
}
